// 把存下来的结果（人物 + 匹配度）展开成结果页需要的全部内容
function buildResult(content, r) {
  const t = content.types[r.type];
  const pick = k => ({ key: k, name: content.types[k].name, seal: content.types[k].seal, color: content.types[k].color, title: content.types[k].title });
  const ranking = Object.keys(r.pct).sort((a, b) => r.pct[b] - r.pct[a]).map(k => ({ ...pick(k), pct: r.pct[k] }));
  const { partner, enemy, ...rest } = t;
  return { at: r.at, type: { key: r.type, ...rest, partner: pick(partner), enemy: pick(enemy) }, ranking };
}
