// 把存下来的结果（人物 + 匹配度 + 四维）展开成结果页需要的全部内容
function buildResult(content, r) {
  const t = content.types[r.type];
  const pick = k => ({ key: k, name: content.types[k].name, seal: content.types[k].seal, color: content.types[k].color, title: content.types[k].title });
  const ranking = Object.keys(r.pct).filter(k => content.types[k]).sort((a, b) => r.pct[b] - r.pct[a]).map(k => ({ ...pick(k), pct: r.pct[k] }));
  const { partner, enemy, ...rest } = t;
  const dims = (r.dims || []).map((x, d) => {
    const D = content.dims[d];
    return { name: D.name, level: D.levels['ABC'.indexOf(x.l)], label: D.labels['ABC'.indexOf(x.l)], parts: ['A', 'B', 'C'].map((l, i) => ({ level: D.levels[i], pct: x[l] })) };
  });
  return {
    at: r.at, total: r.total, same: r.same,
    type: { key: r.type, ...rest, partner: pick(partner), enemy: pick(enemy) },
    ranking, dims,
  };
}
